fails=[]; infos=[]
for l,cmd,cwd,exp,info in cases:
    rc=run(cmd,cwd); b=(rc==2)
    ok = b==exp and rc in (0,2)
    if info: infos.append((l,"BLOCK" if b else "ALLOW", "BLOCK" if exp else "ALLOW"))
    elif not ok: fails.append((l,cmd,exp,rc))
print(f"total={len(cases)} info={len(infos)} fail={len(fails)}")
for f in fails: print("FAIL",f)
for i in infos: print("INFO",i)
# timing
ts=[]
for _ in range(100):
    t=time.perf_counter(); run("git status && git diff --stat | head",R("rfeat")); ts.append((time.perf_counter()-t)*1000)
ts2=[]
for _ in range(100):
    t=time.perf_counter(); run("ls -la docs/",ws); ts2.append((time.perf_counter()-t)*1000)
print("median ms git cmd",statistics.median(ts),"max",max(ts)); print("median ms plain",statistics.median(ts2),"max",max(ts2))
